func applyPOICoords(pois []seedPOI) []seedPOI {
	for i := range pois {
		if c, ok := poiCoords[pois[i].DestinationSlug+"|"+pois[i].Name]; ok {
			pois[i].Lat = c[0]
			pois[i].Lng = c[1]
		} else {
			pois[i].Lat, pois[i].Lng = fallbackCityCoord(pois[i].DestinationSlug, pois[i].Name)
			pois[i].Schematic = true
		}
	}
	return pois
}

func fallbackCityCoord(city, name string) (float64, float64) {
	center, ok := cityCenters[city]
	if !ok {
		center = [2]float64{55.75, 37.62}
	}
	hash := 0
	for _, r := range name {
		hash = hash*31 + int(r)
	}
	if hash < 0 {
		hash = -hash
	}
	lat := center[0] + float64(hash%11-5)*0.004
	lng := center[1] + float64((hash/11)%11-5)*0.004
	return lat, lng
}
